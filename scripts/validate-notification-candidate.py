"""Validate selected runtime in place, then restore byte-identical unrelated files.
No extra checkout; recovery payload is retained in this repo before any changes.
"""
from pathlib import Path
import base64,hashlib,json,os,subprocess,time,shutil
root=Path(__file__).resolve().parents[1];os.chdir(root)
out=root/'docs/evidence/notification-readiness-20261107'
manifest=json.loads((out/'release-manifest.json').read_text());tree=manifest['candidateTree']
paths=[p for p in manifest['excludedChangedSourceAndSharedFiles'] if p.startswith(('src/','tests/','supabase/')) or p=='next-env.d.ts']
def sha(data):return hashlib.sha256(data).hexdigest()
backup={p:base64.b64encode((root/p).read_bytes()).decode() if (root/p).exists() else None for p in paths}
recovery=out/'candidate-source-recovery.json'
# Exclusive create prevents overwriting an unresolved recovery snapshot.
with recovery.open('x') as f:json.dump(backup,f)
expected={};results={};restored=False
try:
 for p in paths:
  old=subprocess.run(['git','show',tree+':'+p],stdout=subprocess.PIPE,stderr=subprocess.DEVNULL)
  expected[p]=old.stdout if old.returncode==0 else None
  if old.returncode==0:(root/p).write_bytes(old.stdout)
  elif (root/p).exists():(root/p).unlink()
 # Selected source and baseline exclusions must exactly match the packaged tree.
 for p in paths:
  assert ((root/p).read_bytes() if (root/p).exists() else None)==expected[p],p
 for item in manifest['files']:
  if item['path'].startswith(('src/','tests/','public/','supabase/')):assert sha((root/item['path']).read_bytes())==item['sha256'],item['path']
 # Cached dev validators can refer to deliberately excluded dev routes.
 shutil.rmtree(root/'.next/dev/types',ignore_errors=True)
 for name,command in [('candidate-check',['npm','run','check']),('candidate-tests',['npm','test'])]:
  started=time.time()
  with (out/(name+'.log')).open('wb') as log:result=subprocess.run(command,stdout=log,stderr=subprocess.STDOUT)
  results[name]={'exitCode':result.returncode,'seconds':round(time.time()-started,1)}
  if result.returncode!=0:break
finally:
 # Do not overwrite concurrent user edits. Retain recovery payload for conflicts.
 conflicts=[]
 for p in paths:
  current=(root/p).read_bytes() if (root/p).exists() else None
  # next-env is deliberately generated by Next; its original snapshot is restored.
  if p!='next-env.d.ts' and p in expected and current!=expected[p]:conflicts.append(p);continue
  content=backup[p]
  if content is None:
   if (root/p).exists():(root/p).unlink()
  else:(root/p).parent.mkdir(parents=True,exist_ok=True);(root/p).write_bytes(base64.b64decode(content))
 if not conflicts:
  for p,content in backup.items():assert ((root/p).read_bytes() if (root/p).exists() else None)==(base64.b64decode(content) if content is not None else None),p
  restored=True;recovery.unlink()
 results.update({'candidateTreeTested':tree,'runtimeTestMigrationSourcesMatched':True,'excludedFilesRestoredByteIdentically':restored,'conflicts':conflicts})
 (out/'candidate-validation.json').write_text(json.dumps(results,indent=2)+'\n')
 print(json.dumps(results))
